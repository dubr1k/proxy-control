/// `OVERRIDE_HEADER`: the first line of the version override the agent owns.
pub const OVERRIDE_HEADER: &str = "# Generated by proxy-control version-agent; do not edit manually.\n";
/// `_download`'s default bound.
pub const MAX_ARTIFACT: u64 = 256 * 1024 * 1024;
/// `TELEMT_BINARY_MAX`.
pub const TELEMT_BINARY_MAX: u64 = 64 * 1024 * 1024;
/// The agent's own restart after its tree changed (`AGENT_RESTART`): systemd restarts the unit five
/// seconds later, after the worker recorded its verdict.
pub const AGENT_RESTART: [&str; 6] =
    ["systemd-run", "--on-active=5", "--unit=proxy-control-version-agent-restart", "systemctl", "restart", "version-agent"];

/// Downloads an approved artifact: `(url, maximum bytes)` → the bytes (`_download`).
pub type Downloader = Arc<dyn Fn(&str, u64) -> Result<Vec<u8>, DownloadError> + Send + Sync>;
/// `time.sleep` (the managers' health wait; tests pass a recorder).
pub type Sleeper = Arc<dyn Fn(f64) + Send + Sync>;
/// `shutil.copy2` of one panel database file (a test seam: Python tests patched `_copy_db_file`).
pub type FileCopy = Arc<dyn Fn(&Path, &Path) -> io::Result<()> + Send + Sync>;

/// Why a step failed: an `UpdateError` (its text is what the caller shows), or any other
/// exception (a command, a file operation, the installer journal), which the caller wraps.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Failure {
    Update(UpdateError),
    Other(Cause),
}

/// A step of an update.
pub type Step<T> = Result<T, Failure>;

impl Failure {
    /// Any other exception, with its Python class name.
    pub fn other(class: impl Into<String>, message: impl Into<String>) -> Failure {
        Failure::Other(Cause { class: class.into(), message: message.into(), stderr: None })
    }

    /// `str(exc)`.
    pub fn message(&self) -> &str {
        match self {
            Failure::Update(error) => &error.message,
            Failure::Other(cause) => &cause.message,
        }
    }

    /// `type(exc).__name__`.
    pub fn class(&self) -> &str {
        match self {
            Failure::Update(error) => error.state.class_name(),
            Failure::Other(cause) => &cause.class,
        }
    }

    /// The chain links this failure contributes to an error raised `from` it.
    pub fn links(&self) -> Vec<Cause> {
        match self {
            Failure::Update(error) => {
                let mut links =
                    vec![Cause { class: error.state.class_name().into(), message: error.message.clone(), stderr: None }];
                links.extend(error.causes.iter().cloned());
                links
            }
            Failure::Other(cause) => vec![cause.clone()],
        }
    }

    /// `except UpdateError: raise / except Exception as exc: raise UpdateError(message) from exc`.
    pub fn into_update(self, message: impl FnOnce() -> String) -> UpdateError {
        match self {
            Failure::Update(error) => error,
            Failure::Other(cause) => UpdateError::new(message()).caused_by(cause),
        }
    }
}

impl fmt::Display for Failure {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.message())
    }
}

impl From<UpdateError> for Failure {
    fn from(error: UpdateError) -> Self {
        Failure::Update(error)
    }
}

impl From<CommandError> for Failure {
    fn from(error: CommandError) -> Self {
        Failure::Other(error.cause())
    }
}

impl From<io::Error> for Failure {
    fn from(error: io::Error) -> Self {
        Failure::other(os_class(&error), os_message(&error))
    }
}

impl From<installer::Error> for Failure {
    fn from(error: installer::Error) -> Self {
        Failure::other(error.python_class_name(), error.message())
    }
}

impl From<pc_host::TxError> for Failure {
    fn from(error: pc_host::TxError) -> Self {
        Failure::other(error.python_class_name(), error.message())
    }
}

/// `str(OSError)` without the file name Python appended: `[Errno 28] No space left on device`.
pub fn os_message(error: &io::Error) -> String {
    match error.raw_os_error() {
        Some(code) => {
            let text = error.to_string();
            let text = text.split(" (os error").next().unwrap_or(&text).to_string();
            format!("[Errno {code}] {text}")
        }
        None => error.to_string(),
    }
}

/// `UpdateError(message)` as a failure.
pub fn refuse(message: impl Into<String>) -> Failure {
    Failure::Update(UpdateError::new(message))
}

/// `raise <error> from <failure>`.
pub fn chained(mut error: UpdateError, failure: &Failure) -> UpdateError {
    error.causes.extend(failure.links());
    error
}

/// The outcome of an update and its rollback (`except Exception as exc: try: <rollback> except
/// Exception: raise RollbackFailedError(unverified) … raise RolledBackError(restored) from exc`).
pub fn rolled_back(exc: Failure, rollback: Step<()>, unverified: String, restored: String) -> Failure {
    match rollback {
        Err(rollback_exc) => {
            let error = chained(UpdateError::rollback_failed(unverified), &rollback_exc);
            Failure::Update(chained(error, &exc))
        }
        Ok(()) => Failure::Update(chained(UpdateError::rolled_back(restored), &exc)),
    }
}

/// The host side of the agent's updates.
#[derive(Clone)]
pub struct HostUpdater {
    pub downloader: Downloader,
    pub sleep: Sleeper,
    /// `platform.machine()`.
    pub machine: String,
    /// `sys.platform`.
    pub system: String,
    pub telemt_binary_max: u64,
    pub copy_db_file: FileCopy,
    /// The panel update and the background manager rebuild (joined at shutdown).
    workers: Arc<Mutex<Vec<JoinHandle<()>>>>,
}

impl fmt::Debug for HostUpdater {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("HostUpdater").field("machine", &self.machine).field("system", &self.system).finish()
    }
}

impl Default for HostUpdater {
    fn default() -> Self {
        HostUpdater::new()
    }
}

/// `platform.machine()`: `uname -m`.
pub fn uname_machine() -> String {
    // SAFETY: `uname` fills a zeroed struct; the fields are NUL-terminated.
    unsafe {
        let mut name: libc::utsname = std::mem::zeroed();
        if libc::uname(&mut name) != 0 {
            return String::new();
        }
        std::ffi::CStr::from_ptr(name.machine.as_ptr()).to_string_lossy().into_owned()
    }
}

impl HostUpdater {
    /// The production updater: HTTPS downloads, real sleeps, this machine.
    pub fn new() -> HostUpdater {
        HostUpdater {
            downloader: Arc::new(|url: &str, maximum: u64| crate::upstream::download_artifact(url, maximum)),
            sleep: Arc::new(|seconds: f64| std::thread::sleep(std::time::Duration::from_secs_f64(seconds.max(0.0)))),
            machine: uname_machine(),
            system: std::env::consts::OS.to_string(),
            telemt_binary_max: TELEMT_BINARY_MAX,
            copy_db_file: Arc::new(|source: &Path, target: &Path| copy2(source, target)),
            workers: Arc::new(Mutex::new(Vec::new())),
        }
    }

    /// The same updater with another downloader (tests).
    pub fn with_downloader(
        downloader: impl Fn(&str, u64) -> Result<Vec<u8>, DownloadError> + Send + Sync + 'static,
    ) -> HostUpdater {
        HostUpdater { downloader: Arc::new(downloader), ..HostUpdater::new() }
    }

    /// `x86_64`/`amd64` (`platform.machine().lower()`).
    pub fn is_x86_64(&self) -> bool {
        matches!(self.machine.to_lowercase().as_str(), "x86_64" | "amd64")
    }

    /// `self.downloader(url)` with Python's error mapping: a refusal is an `UpdateError` with its
    /// text, a network failure any other exception.
    pub fn download(&self, url: &str, maximum: u64) -> Step<Vec<u8>> {
        (self.downloader)(url, maximum).map_err(|error| match error {
            DownloadError::Refused(message) => refuse(message),
            DownloadError::Unreachable(detail) => Failure::other("URLError", format!("<urlopen error {detail}>")),
        })
    }

    /// Starts a background worker and remembers it for [`Updater::wait_idle`].
    pub(crate) fn spawn(&self, name: &str, work: impl FnOnce() + Send + 'static) -> Result<(), AgentError> {
        let handle = std::thread::Builder::new()
            .name(name.into())
            .spawn(work)
            .map_err(|err| AgentError::Internal(format!("{name} could not start: {err}")))?;
        if let Ok(mut workers) = self.workers.lock() {
            workers.retain(|worker| !worker.is_finished());
            workers.push(handle);
        }
        Ok(())
    }

    /// Joins every worker started so far (tests: `agent.panel_thread.join()`).
    pub fn join_workers(&self) {
        let handles: Vec<JoinHandle<()>> = match self.workers.lock() {
            Ok(mut workers) => workers.drain(..).collect(),
            Err(_) => return,
        };
        for handle in handles {
            let _ = handle.join();
        }
    }
}

impl Updater for HostUpdater {
    fn apply(
        &self,
        agent: &Arc<VersionAgent>,
        component: &str,
        entry: &CatalogEntry,
        current: Option<&str>,
    ) -> Result<Applied, UpdateError> {
        let mut applied = Applied::from_entry(entry);
        let outcome: Step<()> = if component == "telemt" {
            telemt::update_telemt(self, agent, entry)
        } else if manager_build(component).is_some() {
            managers::update_manager(self, agent, component, entry, current)
        } else if component == "xray" {
            xray::update_xray(self, agent, entry, current).map(|members| applied.members = Some(members))
        } else if entry.kind == "build" {
            // Built on the host: the pin is whatever the fresh build reports, not something the
            // catalog could know in advance.
            binary::build_caddy(self, agent, entry).and_then(|(payload, runtime_version)| {
                let sha = binary::update_binary(self, agent, component, entry, Some(payload), Some(&runtime_version))?;
                applied.sha256 = Some(sha);
                applied.runtime_version = Some(runtime_version);
                Ok(())
            })
        } else {
            binary::update_binary(self, agent, component, entry, None, None).map(|sha| applied.sha256 = Some(sha))
        };
        outcome.map(|()| applied).map_err(|failure| failure.into_update(|| format!("{component} update failed")))
    }

    fn update_panel(&self, agent: &Arc<VersionAgent>, version: &str, expected: Option<&str>) -> Result<Value, AgentError> {
        panel::update_panel_async(self, agent, version, expected)
    }

    fn rebuild_managers(&self, agent: &Arc<VersionAgent>) -> Result<Value, AgentError> {
        managers::rebuild_managers(self, agent, true)
    }

    fn wait_idle(&self) {
        self.join_workers();
    }
}

