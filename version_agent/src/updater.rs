/// The agent's state directory (`self.state_path.parent`): backups, staging, build directories.
pub fn state_dir(agent: &VersionAgent) -> PathBuf {
    pc_host::fs::py_parent(&agent.config.state_path)
}

/// `_atomic_write(path, content, mode)`.
pub fn atomic_write(path: &Path, data: &[u8], mode: u32) -> io::Result<()> {
    pc_host::fs::atomic_write(path, data, mode, None)
}

/// `path.is_symlink()`.
pub fn is_symlink(path: &Path) -> bool {
    fs::symlink_metadata(path).map(|m| m.file_type().is_symlink()).unwrap_or(false)
}

/// `path.unlink(missing_ok=True)`.
pub fn unlink_missing_ok(path: &Path) -> io::Result<()> {
    match fs::remove_file(path) {
        Err(err) if err.kind() == io::ErrorKind::NotFound => Ok(()),
        other => other,
    }
}

/// `path.read_bytes() if path.exists() else None`.
pub fn read_if_exists(path: &Path) -> io::Result<Option<Vec<u8>>> {
    if path.exists() {
        fs::read(path).map(Some)
    } else {
        Ok(None)
    }
}

/// `os.chmod(path, mode)`.
pub fn chmod(path: &Path, mode: u32) -> io::Result<()> {
    fs::set_permissions(path, fs::Permissions::from_mode(mode))
}

/// The permission bits (`st_mode & 0o777`).
pub fn mode_of(path: &Path) -> io::Result<u32> {
    Ok(fs::metadata(path)?.permissions().mode() & 0o777)
}

/// `shutil.copy2`: the bytes, the permission bits and the access/modification times.
pub fn copy2(source: &Path, target: &Path) -> io::Result<()> {
    let metadata = fs::metadata(source)?;
    fs::copy(source, target)?;
    let times = fs::FileTimes::new().set_accessed(metadata.accessed()?).set_modified(metadata.modified()?);
    fs::OpenOptions::new().write(true).open(target)?.set_times(times)
}

/// `shutil.copyfile` (bytes only; a new file gets the umask mode).
pub fn copyfile(source: &Path, target: &Path) -> io::Result<()> {
    let data = fs::read(source)?;
    fs::write(target, data)
}

/// `_restore_copy`: put a backed-up file back without a cross-directory rename (each
/// `ReadWritePaths` entry of the unit is its own bind mount, so a rename from the state directory
/// into `/usr` fails with EXDEV): copy next to the target, then swap it in.
pub fn restore_copy(backup: &Path, target: &Path, mode: u32) -> io::Result<()> {
    let name = target.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let stage = target.with_file_name(format!(".{name}.proxy-control-restore"));
    let result = (|| {
        copyfile(backup, &stage)?;
        chmod(&stage, mode)?;
        fs::rename(&stage, target)?;
        pc_host::fs::fsync_directory(&pc_host::fs::py_parent(target))
    })();
    let _ = unlink_missing_ok(&stage);
    result
}

/// `_restore_file(path, previous, mode)`: the previous bytes back, or no file when there was none.
pub fn restore_file(path: &Path, previous: Option<&[u8]>, mode: u32) -> io::Result<()> {
    match previous {
        None => unlink_missing_ok(path),
        Some(data) => atomic_write(path, data, mode),
    }
}

/// `_rewrite_env_line(path, key, value)`: set `key=value` in an env overlay in place (the first
/// line wins, duplicates go, a missing key is appended), keeping the other lines and the mode
/// (0600 for a new file). Returns the previous bytes.
pub fn rewrite_env_line(path: &Path, key: &str, value: &str) -> Step<Option<Vec<u8>>> {
    let previous = read_if_exists(path)?;
    let text = match &previous {
        Some(data) => String::from_utf8(data.clone())
            .map_err(|_| Failure::other("UnicodeDecodeError", "'utf-8' codec can't decode the env overlay"))?,
        None => String::new(),
    };
    let prefix = format!("{key}=");
    let mut replaced = false;
    let mut result: Vec<String> = Vec::new();
    for line in crate::py::splitlines(&text) {
        if line.starts_with(&prefix) {
            if !replaced {
                result.push(format!("{key}={value}"));
                replaced = true;
            }
            continue;
        }
        result.push(line.to_string());
    }
    if !replaced {
        result.push(format!("{key}={value}"));
    }
    let mode = if previous.is_some() { mode_of(path)? } else { 0o600 };
    atomic_write(path, format!("{}\n", result.join("\n")).as_bytes(), mode)?;
    Ok(previous)
}

/// The override's text for `_override_with` (`read_text`, an `OSError` reads as empty).
pub fn read_override(path: &Path) -> Step<String> {
    match fs::read(path) {
        Ok(data) => String::from_utf8(data)
            .map_err(|_| Failure::other("UnicodeDecodeError", "'utf-8' codec can't decode the version override")),
        Err(_) => Ok(String::new()),
    }
}

/// `re.fullmatch(r"  ([a-z0-9][a-z0-9_-]*):\s*", line)`: the service name of a block header.
fn block_header(line: &str) -> Option<&str> {
    let rest = line.strip_prefix("  ")?;
    let colon = rest.find(':')?;
    let (name, tail) = (&rest[..colon], &rest[colon + 1..]);
    let mut bytes = name.bytes();
    let first = bytes.next()?;
    let ok = (first.is_ascii_lowercase() || first.is_ascii_digit())
        && bytes.all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_' || b == b'-')
        && tail.chars().all(crate::py::is_space);
    ok.then_some(name)
}

/// `_override_with(override, service, lines)`: the shared version override with one service's
/// block replaced and every other block kept (Telemt's image and the managers' build args live in
/// the same file).
pub fn override_with(text: &str, service: &str, lines: &[String]) -> String {
    let mut blocks: Vec<(String, Vec<String>)> = Vec::new();
    let mut current: Option<usize> = None;
    for line in crate::py::splitlines(text) {
        if let Some(name) = block_header(line) {
            match blocks.iter().position(|(known, _)| known == name) {
                Some(index) => {
                    blocks[index].1.clear();
                    current = Some(index);
                }
                None => {
                    blocks.push((name.to_string(), Vec::new()));
                    current = Some(blocks.len() - 1);
                }
            }
        } else if let Some(index) = current {
            if line.starts_with("    ") {
                blocks[index].1.push(line.to_string());
            }
        }
    }
    match blocks.iter().position(|(known, _)| known == service) {
        Some(index) => blocks[index].1 = lines.to_vec(),
        None => blocks.push((service.to_string(), lines.to_vec())),
    }
    let mut body = String::new();
    for (name, block) in &blocks {
        body.push_str(&format!("  {name}:\n"));
        for line in block {
            body.push_str(line);
            body.push('\n');
        }
    }
    format!("{OVERRIDE_HEADER}services:\n{body}")
}
