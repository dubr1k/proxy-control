/// `self.runner(argv, timeout=…)`.
pub fn run(agent: &VersionAgent, argv: &[String], timeout: u64) -> Result<String, CommandError> {
    agent.runner.run(&Command::new(argv).timeout(timeout))
}

/// `self.runner(argv, cwd=self.compose_dir, timeout=…)`.
pub fn run_compose(agent: &VersionAgent, argv: &[String], timeout: u64) -> Result<String, CommandError> {
    let mut command = Command::new(argv).timeout(timeout);
    command.cwd = agent.config.compose_dir.clone();
    agent.runner.run(&command)
}

/// Owned argv from string slices.
pub fn argv(parts: &[&str]) -> Vec<String> {
    parts.iter().map(|part| part.to_string()).collect()
}

/// The version override (`<compose_dir>/version-overrides/compose.versions.yaml`).
pub fn override_path(agent: &VersionAgent) -> Option<PathBuf> {
    agent.config.compose_dir.as_ref().map(|dir| dir.join("version-overrides").join("compose.versions.yaml"))
}

/// `_override_kwargs()["include_override"]`: the override exists.
pub fn override_exists(agent: &VersionAgent) -> bool {
    override_path(agent).is_some_and(|path| path.exists())
}

/// `_env_files()`: the project env, `.optional.env` when present, then every protocol overlay
/// present, in the installer's order.
pub fn env_files(agent: &VersionAgent) -> Vec<PathBuf> {
    let Some(dir) = &agent.config.compose_dir else { return Vec::new() };
    let mut files = vec![dir.join(".env")];
    // A host may keep optional variables (WARP egress, extra hosts) in `.optional.env` next to
    // `.env`: a Compose call without it would recreate a manager with those settings dropped.
    let optional = dir.join(".optional.env");
    if optional.is_file() {
        files.push(optional);
    }
    for sibling in ["naive", "mieru", "xray-router", "amneziawg", "trusttunnel", "mcp"] {
        let overlay = dir.join(format!(".env.{sibling}"));
        if overlay.is_file() {
            files.push(overlay);
        }
    }
    files
}

fn display(path: &Path) -> String {
    path.to_string_lossy().into_owned()
}

/// `_compose_command(*args, include_override=…, env_files=…)`.
pub fn compose_command(agent: &VersionAgent, args: &[&str], include_override: bool, with_env: bool) -> Step<Vec<String>> {
    let dir = match &agent.config.compose_dir {
        Some(dir) if !agent.config.compose_files.is_empty() => dir.clone(),
        _ => return Err(refuse("Compose deployment is not configured")),
    };
    let mut command = argv(&["docker", "compose", "--project-name"]);
    command.push(agent.project());
    if with_env {
        for file in env_files(agent) {
            command.extend(["--env-file".to_string(), display(&file)]);
        }
    }
    for file in &agent.config.compose_files {
        let path = Path::new(file);
        if path.is_absolute() || path.components().any(|part| part == Component::ParentDir) {
            return Err(refuse("invalid Compose file path"));
        }
        // `self.compose_dir / Path(file)`: `.` and repeated separators fall away.
        let joined = path.components().fold(dir.clone(), |joined, part| match part {
            Component::Normal(name) => joined.join(name),
            _ => joined,
        });
        command.extend(["-f".to_string(), display(&joined)]);
    }
    if include_override {
        command.extend(["-f".to_string(), display(&dir.join("version-overrides").join("compose.versions.yaml"))]);
    }
    command.extend(args.iter().map(|arg| arg.to_string()));
    Ok(command)
}

/// `_compose_up(service)`: recreate one service with the overlays it was installed with and wait
/// for its health (`--no-deps`: the panel depends on the managers, the managers on the data plane).
pub fn compose_up(agent: &VersionAgent, service: &str) -> Step<()> {
    let command = compose_command(agent, &["up", "-d", "--no-deps", "--wait", service], override_exists(agent), true)?;
    run_compose(agent, &command, 300)?;
    Ok(())
}

/// `re.fullmatch(r"sha256:[0-9a-f]{64}", value)`.
pub fn is_image_id(value: &str) -> bool {
    value.strip_prefix("sha256:").is_some_and(crate::catalog::is_sha256)
}

/// `time.strftime("%Y%m%d%H%M%S", time.gmtime())` of the agent's clock.
pub fn stamp(agent: &VersionAgent) -> String {
    let now = (agent.now)().floor() as i64;
    let (year, month, day) = pc_common::logger::civil_from_days(now.div_euclid(86_400));
    let rest = now.rem_euclid(86_400);
    format!("{year:04}{month:02}{day:02}{:02}{:02}{:02}", rest / 3600, rest % 3600 / 60, rest % 60)
}

