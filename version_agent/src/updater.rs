//! What an update does on the host (host WP7): the per-component work behind
//! [`service::Updater`](crate::service::Updater) — `version_agent/service.py:_update_*`,
//! `_build_caddy`, `_update_panel*`, `rebuild_managers` and their helpers.
//!
//! | Module | What | Python |
//! |---|---|---|
//! | this file | [`HostUpdater`], the failure type, Compose argv, env overlays, the override file | `_compose_command`, `_env_files`, `_compose_up`, `_rewrite_env_line`, `_override_with`, `_restore_*` |
//! | [`binary`] | naive and mita on the host: catalog hash, pin, restart with the slots, consumer overlay; the Caddy build | `_update_binary`, `_build_caddy` |
//! | [`telemt`] | Telemt image pin or local build in the version override | `_update_telemt` |
//! | [`xray`] | the router's three pinned files and its running version | `_update_xray` |
//! | [`managers`] | AmneziaWG / TrustTunnel image rebuilds, the `pending_rebuild` rebuild | `_update_manager`, `rebuild_managers` |
//! | [`panel`] | the panel self-update through the installer's ownership handoff, the agent restart | `_update_panel_async`, `_panel_worker`, `_sync_and_restart_panel*` |
//!
//! Every update keeps Python's order of commands, timeouts and texts; the goldens of
//! `tests/fixtures/host-golden/agent/updates/` replay byte for byte.

